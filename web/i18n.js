  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      el.dataset.i18nAttr.split(",").forEach((pair) => {
        const [attr, key] = pair.split("=").map((x) => x.trim());
        if (attr && key) el.setAttribute(attr, t(key));  // "value" on an input the user hasn't typed in updates it too
      });
    });
    const title = document.querySelector("title[data-i18n]");
    if (title) document.title = title.textContent;
    root.querySelectorAll("[data-i18n-toggle]").forEach(toggle);
  }

  function toggle(el) {
    el.classList.add("lang-toggle");
    el.setAttribute("role", "group");
    el.setAttribute("aria-label", t("lang.label"));
    el.replaceChildren(...LANGS.flatMap((l, i) => {
      const b = document.createElement("button");
      b.type = "button"; b.lang = l; b.textContent = NAMES[l];
      b.setAttribute("aria-pressed", String(l === lang));
      b.addEventListener("click", () => setLang(l, true));
      const parts = [b];
      if (i) parts.unshift(Object.assign(document.createElement("span"), { className: "lang-sep", textContent: "|", ariaHidden: "true" }));
      return parts;
    }));
  }

  function setLang(l, remember) {
    if (!LANGS.includes(l) || l === lang) return;
    lang = l;
    document.documentElement.lang = l;
    if (remember) store.set(l);
    const u = new URL(location.href);
    if (u.searchParams.has("lang")) { u.searchParams.set("lang", l); history.replaceState(history.state, "", u); }
    apply();
    listeners.forEach((fn) => { try { fn(l); } catch (e) { console.error(e); } });
  }

