  const LANGS = ["fi", "en"];
  const NAMES = { fi: "Suomi", en: "English" };
  const LOCALE = { fi: "fi-FI", en: "en-GB" };
  const KEY = "sous-lang";
  const store = {
    get() { try { return localStorage.getItem(KEY) || ""; } catch { return ""; } },
    set(v) { try { localStorage.setItem(KEY, v); } catch { /* private mode */ } },
  };

  function detect() {
    const q = (new URLSearchParams(location.search).get("lang") || "").toLowerCase();
    if (LANGS.includes(q)) return q;
    const s = store.get();
    if (LANGS.includes(s)) return s;
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "";
    return /^fi\b/i.test(nav) ? "fi" : "en";
  }

  let lang = detect();
  const listeners = [];
  document.documentElement.lang = lang;

  function t(key, vars) {
    let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k] ?? "") : m));
    return s;
  }

  // --- locale formatting (fi-FI: 1 234,50 €, 15.11.2026 klo 16.45; en-GB: €1,234.50, 15 Nov 2026, 16:45) ---
  const loc = () => LOCALE[lang];
  const pad = (n) => String(n).padStart(2, "0");
  function toDate(v) {
    if (v instanceof Date) return v;
    const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(v || ""));
    return m ? new Date(+m[1], +m[2] - 1, +m[3]) : new Date(v);  // a bare date is a local calendar day
  }
  const ok = (d) => !isNaN(d.getTime());
  function money(n, opts) {
    if (n === null || n === undefined || n === "") return "";
    return new Intl.NumberFormat(loc(), { style: "currency", currency: (opts && opts.currency) || "EUR", ...(opts || {}) }).format(Number(n));
  }
  function num(n, opts) {
    if (n === null || n === undefined || n === "") return "";
    return typeof n === "number" || /^-?\d+(\.\d+)?$/.test(String(n)) ? new Intl.NumberFormat(loc(), opts).format(Number(n)) : String(n);
  }
  function time(v) {
    const d = toDate(v); if (!ok(d)) return String(v || "");
    return lang === "fi" ? `${d.getHours()}.${pad(d.getMinutes())}` : `${pad(d.getHours())}:${pad(d.getMinutes())}`;
  }
  function date(v, opts) {
    const d = toDate(v); if (!ok(d)) return String(v || "");
    const wd = opts && opts.weekday ? new Intl.DateTimeFormat(loc(), { weekday: "short" }).format(d) + " " : "";
    return lang === "fi" ? `${wd}${d.getDate()}.${d.getMonth() + 1}.${d.getFullYear()}`
      : wd + new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", year: "numeric" }).format(d);
  }
  function dateTime(v) {
    const d = toDate(v); if (!ok(d)) return String(v || "");
    return lang === "fi" ? `${date(d)} klo\u00a0${time(d)}` : `${date(d)}, ${time(d)}`;
  }
  // Short form for deadlines this week: "la 14.11. klo 14.08" / "Sat 14 Nov, 14:08".
  function dayTime(v) {
    const d = toDate(v); if (!ok(d)) return String(v || "");
    const wd = new Intl.DateTimeFormat(loc(), { weekday: "short" }).format(d);
    return lang === "fi" ? `${wd} ${d.getDate()}.${d.getMonth() + 1}. klo\u00a0${time(d)}`
      : `${wd} ${new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short" }).format(d)}, ${time(d)}`;
  }
  const unit = (code) => (code && STRINGS.en["unit." + code] ? t("unit." + code) : String(code || ""));
  const tier = (name) => t("tier." + name);

